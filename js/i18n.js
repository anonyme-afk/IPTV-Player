const Lang = (() => {
  const detected = (navigator.language || navigator.userLanguage || 'en').split('-')[0].toLowerCase();
  const current  = I18N[detected] ? detected : 'en';

  function t(key) {
    return (I18N[current] && I18N[current][key]) || (I18N.en[key]) || key;
  }

  function apply() {
    // Set dir for RTL languages
    document.documentElement.setAttribute('lang', current);
    document.documentElement.setAttribute('dir', current === 'ar' ? 'rtl' : 'ltr');

    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.innerHTML = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
  }

  return { t, apply, current };
})();
